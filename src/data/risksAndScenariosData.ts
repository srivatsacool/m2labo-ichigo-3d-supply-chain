function buildScenario(
  id: string,
  title: string,
  milestoneId: string,
  linkedMilestones: string[],
  severityBand: 'CRITICAL' | 'HIGH' | 'MODERATE',
  overview: string,
  trigger: string,
  initialWarning: string,
  symptoms: string[],
  responsibleRole: string,
  customerCommunication: string,
  financialImpact: string,
  recoveryOptions: string[],
  decisionPrompt: string,
  branchA: { label: string; consequence: string; path: string },
  branchB: { label: string; consequence: string; path: string }
): ScenarioSimulation {
  return {
    id,
    title,
    milestoneId,
    linkedMilestones,
    severityBand,
    overview,
    trigger,
    initialWarning,
    observableSymptoms: symptoms,
    responsibleRole,
    responseTimeTarget: 'UNKNOWN / NEEDS VERIFICATION (SLA target unconfirmed)',
    requiredEvidence: ['Timestamped exception log', 'Linked Batch/Order/Shipment QR', 'Photo/Thermal trace evidence', 'Supervisor approval note'],
    recoveryOptions,
    customerCommunication,
    financialImpact,
    closureCriteria: 'Root cause documented, customer/stock disposition closed, and financial impact reconciled in M11.',
    status: 'ILLUSTRATIVE SIMULATION',
    sequence: [
      { phase: 'TRIGGER', actor: 'Process Event', action: trigger, recordOrEvidence: 'Event timestamp logged' },
      { phase: 'DETECTION', actor: 'Frontline Operator / Sensor', action: initialWarning, recordOrEvidence: 'Inspection flag / Alert ID' },
      { phase: 'IMMEDIATE_ACTION', actor: 'Station Worker', action: `Isolate impacted batch/order at ${milestoneId} and freeze further downstream progression.`, recordOrEvidence: 'QR Hold Status' },
      { phase: 'NOTIFICATION', actor: 'Supervisor / Automated Alert', action: `Escalate immediately to ${responsibleRole} with affected IDs.`, recordOrEvidence: 'Escalation notice timestamp' },
      { phase: 'ASSESSMENT', actor: `${responsibleRole} + QC`, action: 'Evaluate food safety, thermal integrity, grade compliance and SLA exposure.', recordOrEvidence: 'QC Assessment Sheet' },
      { phase: 'DECISION', actor: responsibleRole, action: `Select recovery path: ${recoveryOptions[0]} vs ${recoveryOptions[1] || 'Hold/Scrap'}.`, recordOrEvidence: 'Signed Decision Gate' },
      { phase: 'RECOVERY', actor: 'Ops / Logistics / Farm Team', action: recoveryOptions[0], recordOrEvidence: 'Recovery execution log' },
      { phase: 'CLOSURE', actor: 'Ops & Finance', action: 'Close exception ticket, update inventory bucket & reconcile margin impact in M11.', recordOrEvidence: 'Closed Audit Record' },
    ],
    decisionTree: [
      {
        id: `${id}-N1`,
        question: decisionPrompt,
        options: [
          {
            label: branchA.label,
            consequence: branchA.consequence,
            recoveryPath: branchA.path,
            finalOutcome: `Execute ${branchA.label} → Close under ${responsibleRole} sign-off (ILLUSTRATIVE).`,
          },
          {
            label: branchB.label,
            consequence: branchB.consequence,
            recoveryPath: branchB.path,
            finalOutcome: `Execute ${branchB.label} → Escalate to Ops Head & log in M10/M11 (ILLUSTRATIVE).`,
          },
        ],
      },
    ],
  };
}

